# Generate stubs.c: one default entry per EAGL dispatch slot (1036 slots).
# Input: gl-dispatch-slots.txt ("0xOFS slot N glName 0xADDR", from tools/gl_slots.py).
import sys

NSLOTS = 1036
names = {}
for line in open(sys.argv[1]):
    p = line.split()
    if len(p) >= 4 and p[1] == 'slot':
        n = int(p[2])
        names.setdefault(n, p[3])

out = open(sys.argv[2], 'w')
out.write('/* generated by gen.py */\n#include <stdint.h>\n')
out.write('#define SWEETGL_NSLOTS %d\n' % NSLOTS)
out.write('extern uint64_t sweetgl_hit(int slot);\n')
for i in range(NSLOTS):
    out.write('static uint64_t s%d(void) { return sweetgl_hit(%d); }\n' % (i, i))
out.write('void *const sweetgl_default[%d] = {\n' % NSLOTS)
for i in range(NSLOTS):
    out.write('\t(void *)s%d,\n' % i)
out.write('};\n')
out.write('const char *const sweetgl_slot_name[%d] = {\n' % NSLOTS)
for i in range(NSLOTS):
    out.write('\t"%s",\n' % names.get(i, 'slot%d' % i))
out.write('};\n')
